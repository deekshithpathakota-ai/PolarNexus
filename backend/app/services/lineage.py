"""Provenance pipeline (lineage): Source → Ingestion → Processing → Transformation → AI Generation → Human Review → Publication.

Every stage is derived from stored facts (provenance rows, version history, ingestion jobs, citations, reviews and
timestamps). A stage with no recorded evidence is returned with state "not_applicable" or "pending" — it is never
filled in with an assumed date or actor.
"""
from __future__ import annotations

from collections import OrderedDict

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Document, GeneratedContent, IngestionJob, ResourceVersion
from app.services import provenance as prov


def _iso(v):
    return v.isoformat() if v else None


def _stage(key, label, state, detail="", at=None, actor=""):
    return {"key": key, "label": label, "state": state, "detail": detail, "at": _iso(at), "actor": actor}


def content_lineage(db: Session, c: GeneratedContent) -> dict:
    grouped: OrderedDict[tuple[str, int], dict] = OrderedDict()
    for cit in c.citations:
        key = (cit.resource_type, cit.resource_id)
        g = grouped.setdefault(key, {"type": cit.resource_type, "id": cit.resource_id, "slug": cit.resource_slug,
                                     "title": cit.label.split(" — ")[0], "citations": 0, "sections": [], "pages": []})
        g["citations"] += 1
        if cit.section and cit.section not in g["sections"]:
            g["sections"].append(cit.section)
        if cit.page and cit.page not in g["pages"]:
            g["pages"].append(cit.page)
    sources = list(grouped.values())
    from app.services.catalog import resource_url

    for s in sources:
        try:
            s["url"] = resource_url(s["type"], s["slug"]) if s["slug"] else ""
        except KeyError:
            s["url"] = ""
        model = prov.MODELS.get(s["type"])
        obj = db.get(model, s["id"]) if model else None
        if obj is not None:
            p = prov.get_provenance(db, s["type"], obj)
            s["verification_status"], s["verification_label"] = p["verification_status"], p["verification_label"]
    reviews = sorted(c.reviews, key=lambda r: r.created_at or c.created_at)
    submitted = next((r for r in reviews if r.action == "submitted"), None)
    decisions = [r for r in reviews if r.action in {"approved", "rejected", "changes_requested"}]
    published = next((r for r in reviews if r.action == "published"), None)
    check = c.evidence_check or {}
    stages = [
        _stage("source", "Source", "done" if sources else "missing",
               f"{len(sources)} repository record(s), {len(c.citations)} cited passage(s)" if sources else "No cited sources"),
        _stage("ingestion", "Ingestion", "done" if sources else "not_applicable",
               "Sources were ingested and indexed in the repository before generation"),
        _stage("processing", "Processing", "done" if sources else "not_applicable",
               "Passages retrieved from the hybrid (keyword + vector) index"),
        _stage("transformation", "Transformation", "done",
               f"Format: {c.format}" + (f" · audience: {c.audience}" if c.audience else "")
               + (f" · translation of #{c.translated_from}" if c.translated_from else "")),
        _stage("generation", "AI Generation", "done",
               {"llm": "Generated by the configured language model", "template": "Assembled from source sentences (template)",
                "curated_demo": "Prepared demonstration content", "manual": "Written manually"}.get(c.generation_mode, c.generation_mode)
               + (f" · evidence check: {check.get('overall')}" if check.get("overall") else ""), c.created_at),
        _stage("review", "Human Review",
               "done" if c.status in {"approved", "published"} else "rejected" if c.status == "rejected"
               else "in_progress" if c.status in {"under_review", "changes_requested"} else "pending",
               (decisions[-1].action.replace("_", " ").capitalize() + (f" — {decisions[-1].comment}" if decisions[-1].comment else ""))
               if decisions else ("Submitted for review" if submitted else "Not yet submitted"),
               (decisions[-1].created_at if decisions else submitted.created_at if submitted else None),
               decisions[-1].reviewer_name if decisions else ""),
        _stage("publication", "Publication", "done" if c.status == "published" else "pending",
               ("Published to " + ", ".join(c.channels or ["website"])) if c.status == "published" else "Not published",
               c.published_at, published.reviewer_name if published else ""),
    ]
    return {"kind": "content", "id": c.id, "title": c.title, "stages": stages, "generated_from": sources}


def resource_lineage(db: Session, rtype: str, obj) -> dict:
    p = prov.get_provenance(db, rtype, obj)
    versions = db.scalars(select(ResourceVersion).where(ResourceVersion.resource_type == rtype,
                                                        ResourceVersion.resource_id == obj.id)
                          .order_by(ResourceVersion.version)).all()
    first = versions[0] if versions else None
    job = None
    if rtype == "document":
        job = db.scalar(select(IngestionJob).where(IngestionJob.document_id == obj.id).order_by(IngestionJob.created_at.desc()))
    processing = "Indexed for keyword and semantic search"
    if rtype == "document" and isinstance(obj, Document):
        processing = f"{len(obj.chunks)} passages indexed" + (f" · OCR: {obj.ocr_status}" if obj.ocr_status else "")
    elif rtype == "media":
        processing = f"Processing: {obj.processing_status or 'ready'}" + (f" · visual index: {obj.visual_status}" if obj.visual_status else "")
    elif rtype == "dataset":
        processing = f"{obj.record_count:,} records registered" + (" · schema validated" if obj.columns_schema else "")
    stages = [
        _stage("source", "Source", "done" if p.get("source_organisation") or p.get("source_url") else "missing",
               p.get("source_organisation") or "Source not recorded"),
        _stage("ingestion", "Ingestion", "done", (first.change if first else "Imported") +
               (f" · job #{job.id} {job.status}" if job else ""), (first.created_at if first else p.get("imported_at") and None),
               first.user_name if first else ""),
        _stage("processing", "Processing", "done", processing),
        _stage("verification", "Verification", "done" if p["verification_status"] in prov.TRUSTED_STATUSES else
               "info" if p["verification_status"] in {"public_source", "user_uploaded"} else "demo"
               if p["is_demo"] else "pending", p["verification_label"], None, p.get("verified_by") or ""),
    ]
    return {"kind": rtype, "id": obj.id, "stages": stages, "versions": len(versions)}
